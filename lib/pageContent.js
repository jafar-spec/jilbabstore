// Editable informational pages. Content is stored in Firestore (`pages/{slug}`)
// and managed from the admin panel; these are the fallback defaults shown until
// an admin edits them. Each page = { title, blocks: [{ heading, body }] } for
// the Arabic (base) content, plus an optional `he: { title, blocks }` for the
// Hebrew variant. `body` may contain multiple lines (each renders as a paragraph).
// Pick the variant for the current language with resolvePage(data, lang).
export const resolvePage = (data, lang = 'ar') => {
  if (!data) return { title: '', blocks: [] };
  if (lang === 'he' && data.he && (data.he.title || (data.he.blocks || []).length)) {
    return { title: data.he.title || data.title || '', blocks: data.he.blocks || data.blocks || [] };
  }
  // English (and anything else) falls back to the Arabic base content.
  return { title: data.title || '', blocks: data.blocks || [] };
};

